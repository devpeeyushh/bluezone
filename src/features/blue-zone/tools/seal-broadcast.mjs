// Offline helper (Node, not bundled): seals the Emergency Broadcast final answer and the Radio
// Communication dataset into data/broadcast/sealedDataset.ts. Neither the answer nor the dataset is
// stored in plaintext: the answer is a salted SHA-256 check, and the dataset is XORed with a
// keystream derived from the correct answer, so it can only be opened by solving the puzzle.
//
//   node src/features/blue-zone/tools/seal-broadcast.mjs "<ANSWER>" <dataset.csv> [download-name]
//
// The answer is normalised exactly like utils/finalAnswer.normalizeFinalAnswer.

import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { basename, dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const [rawAnswer, datasetPath, downloadName] = process.argv.slice(2);
if (!rawAnswer || !datasetPath) {
  console.error('usage: seal-broadcast.mjs "<ANSWER>" <dataset.csv> [download-name]');
  process.exit(1);
}

const normalize = (raw) => {
  return raw.trim().toUpperCase();
};

const answer = normalize(rawAnswer);
const sha = (text) => createHash("sha256").update(text).digest();
const data = readFileSync(datasetPath);
const sealed = Buffer.alloc(data.length);
for (let i = 0, block = 0; i < data.length; i += 32, block++) {
  const keystream = sha(`bluezone:emergency-broadcast:dataset:${answer}:${block}`);
  for (let j = 0; j < 32 && i + j < data.length; j++) sealed[i + j] = data[i + j] ^ keystream[j];
}

const out = join(dirname(fileURLToPath(import.meta.url)), "..", "data", "broadcast", "sealedDataset.ts");
const b64 = sealed.toString("base64");
writeFileSync(
  out,
  `// Generated by tools/seal-broadcast.mjs. Do not edit by hand.
// Emergency Broadcast final answer check and the sealed Radio Communication dataset (opened only
// with the correct answer; see utils/finalAnswer.ts).

export const FINAL_ANSWER_CHECK = "${sha(`bluezone:emergency-broadcast:verify:${answer}`).toString("hex")}";

export const DATASET_FILENAME = ${JSON.stringify(downloadName || basename(datasetPath))};
export const DATASET_BYTES = ${data.length};
export const DATASET_SHA256 = "${sha(data).toString("hex")}";

export const SEALED_DATASET =
${b64.match(/.{1,120}/g).map((l) => `  "${l}"`).join(" +\n")};
`
);
console.log(`sealed ${data.length} bytes -> ${out}`);
